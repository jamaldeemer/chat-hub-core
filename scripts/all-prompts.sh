#!/bin/sh
# Rebuild docs/all-prompts.md: every prompt the plugin gives Claude, in one file to read.
set -e
cd "$(dirname "$0")/.."
out=docs/all-prompts.md
{
  echo "# chat-hub-core: every prompt in the plugin"
  echo
  echo "Generated by scripts/all-prompts.sh on $(date +%Y-%m-%d). Edit the source files, not this one."
  for f in skills/setup/SKILL.md skills/hub/SKILL.md skills/work-chat/SKILL.md templates/brief.md templates/wrap-up.md; do
    printf '\n---\n\n## `%s`\n\n````markdown\n' "$f"
    cat "$f"
    printf '````\n'
  done
  printf '\n---\n\n## Hook messages (text the hooks add to a chat)\n'
  for f in hooks/session-start.mjs hooks/on-prompt.mjs hooks/before-commit.mjs hooks/guard.mjs hooks/usage.mjs hooks/after-turn.mjs; do
    printf '\nFrom `%s`:\n\n```js\n' "$f"
    grep -hE "say\(|deny\(|systemMessage|^ *['\`\"].*[a-z].*['\`\"] *[+,)]? *$|^ *\? \`|^ *: \`" "$f" | grep -v '^ *//' || true
    printf '```\n'
  done
  printf '\nFrom `githooks/pre-push` (shown when a push to main is refused):\n\n```\n'
  grep -o 'echo "[^"]*"' githooks/pre-push | sed 's/^echo //'
  printf '```\n'
} > "$out"
